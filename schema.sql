-- Oracle schema for the Agenda app (run as AGENDA_USER)
CREATE TABLE EVENEMENT (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TITRE VARCHAR2(100),
  DATE_EVENEMENT DATE,
  HEURE VARCHAR2(5),
  DESCRIPTION VARCHAR2(500),
  TYPE_EVENEMENT VARCHAR2(50),
  IMPORTANT NUMBER(1,0) DEFAULT 0
);
